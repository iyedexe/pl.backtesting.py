"""The five asset-class studies.

Each study produces, under ``research/reports/``:

- ``figures/<study>_*.png``      report figures
- ``tables/<study>_*.csv``       machine-readable result tables
- ``_fragments/<study>.md``      a markdown fragment stitched by ``report.py``

Every performance number in a fragment is **out-of-sample** (walk-forward with
formation-only estimation and next-close execution) unless explicitly labeled
in-sample/descriptive.
"""

from __future__ import annotations

import json
from dataclasses import replace
from pathlib import Path

import numpy as np
import pandas as pd

from . import data, plotting
from .config import (
    DEFAULT_COSTS_BP,
    PERIODS_PER_YEAR,
    SignalConfig,
    WalkForwardConfig,
    engine_config_for,
)
from .metrics import deflated_sharpe_ratio, summarize_walkforward
from .screening import expected_false_positives, screen_panel
from .stats import engle_granger
from .walkforward import walk_forward_pair, walk_forward_portfolio

REPORTS = data._REPO_ROOT / 'research' / 'reports'
FIG = REPORTS / 'figures'
TAB = REPORTS / 'tables'
FRAG = REPORTS / '_fragments'

SIG_DEFAULT = SignalConfig(entry=2.0, exit=0.0, stop=4.0, z_window=60)
WF_DEFAULT = WalkForwardConfig(formation=252, trading=63)

#: Featured pairs per study: (y-leg, x-leg, panel used for the legs).
FEATURED = {
    'crypto': [('BTC', 'ETH', 'crypto'), ('LTC', 'ETH', 'crypto')],
    'stocks': [('KO', 'PEP', 'stocks'), ('XOM', 'CVX', 'stocks'),
               ('V', 'MA', 'stocks'), ('JPM', 'BAC', 'stocks'),
               ('HD', 'LOW', 'stocks'), ('GOOGL', 'GOOG', 'stocks')],
    'forex': [('AUD', 'NZD', 'forex'), ('EUR', 'GBP', 'forex'),
              ('SEK', 'NOK', 'forex')],
    'commodities': [('WTI', 'BRENT', 'commodities'),
                    ('NATGAS', 'WTI', 'commodities')],
    'cross': [('CAD', 'WTI', 'cross'), ('BTC', 'PAXG', 'cross')],
}

STUDY_START = {
    'crypto': '2016-01-01',     # ETH liquid from late 2015
    'stocks': None,             # panel is 2013-2018 by construction
    'forex': '1999-01-04',      # post-euro
    'commodities': '1990-01-01',
    'cross': '1990-01-01',      # per-pair inner joins trim this naturally
}

G10_FX = ['EUR', 'GBP', 'CHF', 'SEK', 'NOK', 'DKK', 'AUD', 'NZD', 'CAD',
          'JPY', 'SGD']

SCREEN_PARAMS = {  # corr_min, min_obs, max_pairs_tested
    'crypto': (0.5, 750, None),
    'stocks': (0.6, 1000, 6000),
    'forex': (0.5, 2500, None),
    'commodities': (0.3, 2500, None),
    'cross': (0.3, 750, None),
}


def _ensure_dirs():
    for d in (FIG, TAB, FRAG):
        d.mkdir(parents=True, exist_ok=True)


def _md_table(df: pd.DataFrame, floatfmt: str = '.2f') -> str:
    return df.to_markdown(floatfmt=floatfmt)


def study_panel(study: str, quick: bool = False) -> pd.DataFrame:
    """Wide close panel used for the *screening* stage of one study."""
    if study == 'forex':
        panel = data.load_panel('forex')[G10_FX]
    elif study == 'cross':
        pieces = {
            'BTC': data.get_series('crypto', 'BTC'),
            'ETH': data.get_series('crypto', 'ETH'),
            'PAXG': data.get_series('crypto', 'PAXG'),
            'WTI': data.get_series('commodities', 'WTI'),
            'BRENT': data.get_series('commodities', 'BRENT'),
            'NATGAS': data.get_series('commodities', 'NATGAS'),
            'CAD': data.get_series('forex', 'CAD'),
            'AUD': data.get_series('forex', 'AUD'),
            'NOK': data.get_series('forex', 'NOK'),
        }
        panel = pd.concat(pieces, axis=1)
    else:
        panel = data.load_panel(study)
    start = STUDY_START.get(study)
    if start:
        panel = panel.loc[panel.index >= start]
    if quick and study == 'stocks':
        rng = np.random.default_rng(42)
        cols = sorted(rng.choice(panel.columns, size=80, replace=False))
        keep = sorted(set(cols) | {a for a, b, _ in FEATURED['stocks']}
                      | {b for a, b, _ in FEATURED['stocks']})
        panel = panel[[c for c in keep if c in panel.columns]]
    return panel


def _wf(prices, sig, eng, wf, name):
    return walk_forward_pair(prices, sig, eng, wf, name=name)


def _featured_prices(a: str, b: str, panel_name: str, study: str) -> pd.DataFrame:
    return data.aligned_pair(panel_name, a, b, start=STUDY_START.get(study))


def run_study(study: str, quick: bool = False) -> Path:
    """Run one study end to end; returns the path of its markdown fragment."""
    _ensure_dirs()
    ppy = PERIODS_PER_YEAR[study]
    base_cost = DEFAULT_COSTS_BP[study]
    eng = engine_config_for(study)
    wf_cfg = WF_DEFAULT
    md: list[str] = [f'<!-- generated by `pairs run --study {study}` -->']

    # ------------------------------------------------------------------ screen
    panel = study_panel(study, quick=quick)
    corr_min, min_obs, cap = SCREEN_PARAMS[study]
    scr = screen_panel(panel, corr_min=corr_min, min_obs=min_obs,
                       max_pairs_tested=cap)
    scr.to_csv(TAB / f'{study}_screen.csv', index=False)
    n_assets = panel.shape[1]
    fig_scr = plotting.screening_scatter(
        scr, f'{study}: Engle-Granger screen, {n_assets} assets '
             f'({len(scr)} pairs past corr ≥ {corr_min})',
        FIG / f'{study}_screen.png', hl_max=wf_cfg.max_half_life)
    md.append(f'\n### Universe screen ({study})\n')
    md.append(
        f'{n_assets} assets, {panel.index.min().date()} → '
        f'{panel.index.max().date()}; {len(scr)} pairs pass the correlation '
        f'prefilter (≥ {corr_min}); '
        f'{(scr["eg_pvalue"] < 0.05).sum()} of them reject the Engle-Granger null '
        f'at 5%. With {n_assets * (n_assets - 1) // 2} candidate pairs, '
        f'≈ {expected_false_positives(n_assets):.0f} would pass at 5% by pure '
        f'chance (Clegg 2014), so this screen is *descriptive*: performance '
        f'claims come only from the walk-forward section below.\n')
    top = scr.head(10).copy()
    md.append(_md_table(top.set_index(top['y'] + '/' + top['x'])
                        [['corr', 'eg_pvalue', 'beta', 'half_life', 'hurst',
                          'n_obs']], floatfmt='.3f'))
    md.append(f'\n![screen](figures/{Path(fig_scr).name})\n')

    # ------------------------------------------------- featured pair deep dives
    overview_rows = []
    persist_rows = []
    cost_curves: dict[str, pd.Series] = {}
    for a, b, panel_name in FEATURED[study]:
        name = f'{a}/{b}'
        try:
            prices = _featured_prices(a, b, panel_name, study)
        except (KeyError, ValueError) as e:
            md.append(f'\n*{name}: skipped ({e})*\n')
            continue
        eg_full = engle_granger(prices['a'], prices['b'], names=(a, b),
                                try_both_orientations=False)

        wf_res = _wf(prices, SIG_DEFAULT, eng, wf_cfg, name)
        summ = summarize_walkforward(wf_res, ppy)
        overview_rows.append(summ)

        # descriptive full-sample overlay figure (labeled as such)
        la, lb = np.log(prices['a']), np.log(prices['b'])
        spread_full = la - eg_full.alpha - eg_full.beta * lb
        from .signals import zscore
        z_full = zscore(spread_full, SIG_DEFAULT.z_window)
        slice_ = prices.index[-min(len(prices), ppy * 4):]
        fig_pair = plotting.pair_overview(
            prices.loc[slice_], spread_full.loc[slice_], z_full.loc[slice_],
            wf_res.trades[wf_res.trades['entry_date'].isin(slice_)],
            (a, b), SIG_DEFAULT.entry, SIG_DEFAULT.stop,
            f'{name} — last {len(slice_)} bars '
            f'(spread/z shown with full-sample β={eg_full.beta:.2f} for '
            f'illustration; trades are from the walk-forward run)',
            FIG / f'{study}_{a}_{b}_overview.png')
        md.append(f'\n### {name}\n')
        md.append(
            f'Full-sample descriptives: EG p={eg_full.pvalue:.3f}, '
            f'β={eg_full.beta:.2f}, half-life={eg_full.half_life:.1f} bars, '
            f'Hurst={eg_full.hurst:.2f}, n={eg_full.n_obs}. '
            f'Walk-forward gate open {100 * wf_res.gate_pass_rate:.0f}% of '
            f'{len(wf_res.windows)} windows.\n')
        md.append(f'\n![{name}](figures/{Path(fig_pair).name})\n')

        # estimator / z-mode / execution-lag variants
        variants = {
            'OLS + rolling z (default)': wf_res,
            'OLS + frozen z (GGR)': _wf(prices, SIG_DEFAULT, eng,
                                        replace(wf_cfg, z_mode='frozen'), name),
            'Kalman hedge': _wf(prices, SIG_DEFAULT, eng,
                                replace(wf_cfg, use_kalman=True), name),
            'same-close execution (lag 0)': _wf(prices, SIG_DEFAULT,
                                                replace(eng, execution_lag=0),
                                                wf_cfg, name),
            'no gate': _wf(prices, SIG_DEFAULT, eng,
                           replace(wf_cfg, gate=False), name),
        }
        vtab = pd.DataFrame({k: summarize_walkforward(v, ppy)
                             for k, v in variants.items()}).T
        vtab = vtab[['sharpe', 'cagr_pct', 'max_dd_pct', 'n_trades',
                     'win_rate_pct', 'avg_trade_bp', 'nw_tstat',
                     'gate_pass_pct', 'exposure_pct']]
        vtab.to_csv(TAB / f'{study}_{a}_{b}_variants.csv')
        md.append('\nMethod variants (all out-of-sample, base costs '
                  f'{base_cost:.0f} bp/side):\n')
        md.append(_md_table(vtab))
        md.append('')

        # equity curves for the main variants
        fig_eq = plotting.equity_curves(
            {'OLS (default)': wf_res.equity,
             'Kalman': variants['Kalman hedge'].equity,
             'no gate': variants['no gate'].equity},
            f'{name}: out-of-sample walk-forward equity',
            FIG / f'{study}_{a}_{b}_equity.png')
        md.append(f'\n![equity](figures/{Path(fig_eq).name})\n')

        fig_gate = plotting.gate_timeline(
            wf_res.windows, f'{name}: cointegration gate by window '
            f'(formation EG p<{wf_cfg.coint_pvalue_gate}, '
            f'half-life {wf_cfg.min_half_life:.0f}-{wf_cfg.max_half_life:.0f} bars)',
            FIG / f'{study}_{a}_{b}_gate.png')
        md.append(f'\n![gate](figures/{Path(fig_gate).name})\n')

        # gate persistence (Clegg-style)
        w = wf_res.windows
        if len(w) > 4:
            passed = w['traded'].to_numpy()
            if passed[:-1].sum() > 0:
                p_next = float(passed[1:][passed[:-1]].mean())
            else:
                p_next = float('nan')
            persist_rows.append({'pair': name, 'windows': len(w),
                                 'pass_rate': float(passed.mean()),
                                 'p_pass_given_pass': p_next})

        # threshold sensitivity grid + deflated Sharpe
        if not quick:
            entries = [1.0, 1.5, 2.0, 2.5]
            exits = [0.0, 0.5, 0.75]
            grid = pd.DataFrame(index=pd.Index(entries, name='entry z'),
                                columns=pd.Index(exits, name='exit z'),
                                dtype=float)
            trial_srs = []
            for e_ in entries:
                for x_ in exits:
                    r = _wf(prices, replace(SIG_DEFAULT, entry=e_, exit=x_),
                            eng, wf_cfg, name)
                    s = summarize_walkforward(r, ppy)
                    grid.loc[e_, x_] = s['sharpe']
                    rr = r.returns.to_numpy()
                    sd = rr.std(ddof=1)
                    trial_srs.append(rr.mean() / sd if sd > 0 else np.nan)
            fig_grid = plotting.sensitivity_heatmap(
                grid, f'{name}: OOS Sharpe by entry/exit threshold',
                FIG / f'{study}_{a}_{b}_grid.png')
            dsr = deflated_sharpe_ratio(wf_res.returns, np.asarray(trial_srs))
            md.append(
                f'\nThreshold sensitivity (12 configurations). Deflated Sharpe '
                f'probability of the default cell, accounting for this grid '
                f'search: **{dsr:.2f}**.\n')
            md.append(f'\n![grid](figures/{Path(fig_grid).name})\n')

        # cost sweep
        sweep = {}
        for bp in [0.0, base_cost / 2, base_cost, 2 * base_cost, 4 * base_cost]:
            r = _wf(prices, SIG_DEFAULT, engine_config_for(study, cost_bp=bp),
                    wf_cfg, name)
            sweep[bp] = summarize_walkforward(r, ppy)['sharpe']
        cost_curves[name] = pd.Series(sweep)

    if cost_curves:
        cc = pd.DataFrame(cost_curves)
        cc.index.name = 'per_side_bp'
        cc.to_csv(TAB / f'{study}_cost_sweep.csv')
        fig_cost = plotting.cost_sensitivity(
            cc, f'{study}: cost sensitivity (base = {base_cost:.0f} bp/side)',
            FIG / f'{study}_costs.png')
        md.append('\n### Cost sensitivity\n')
        md.append(f'\n![costs](figures/{Path(fig_cost).name})\n')

    if overview_rows:
        ov = pd.DataFrame(overview_rows)
        ov.to_csv(TAB / f'{study}_overview.csv')
        md.insert(1, '\n'.join([
            f'\n## {study.capitalize()}\n',
            f'Featured pairs, default rule (enter 2σ / exit 0 / stop 4σ, '
            f'{wf_cfg.formation}d formation, {wf_cfg.trading}d trading, '
            f'next-close execution, {base_cost:.0f} bp/side):\n',
            _md_table(ov[['sharpe', 'cagr_pct', 'ann_vol_pct', 'max_dd_pct',
                          'n_trades', 'win_rate_pct', 'avg_trade_bp',
                          'converged_pct', 'nw_tstat', 'gate_pass_pct',
                          'years']]),
            '',
        ]))

    if persist_rows:
        pr = pd.DataFrame(persist_rows).set_index('pair')
        pr.to_csv(TAB / f'{study}_persistence.csv')
        md.append('\n### Does the cointegration gate persist?\n')
        md.append(
            'Fraction of formation windows passing the gate, and the '
            'probability of passing again next window given a pass now '
            '(Clegg 2014 asks whether the second number beats the first):\n')
        md.append(_md_table(pr, floatfmt='.2f'))
        md.append('')

    # ------------------------------------------------------- portfolio studies
    if study in ('crypto', 'stocks') and not quick:
        top_n = 3 if study == 'crypto' else 10
        pf_corr = 0.6 if study == 'crypto' else 0.9
        pf = walk_forward_portfolio(panel, SIG_DEFAULT, eng, wf_cfg,
                                    select_top=top_n, corr_min=pf_corr,
                                    name=f'{study} top-{top_n}')
        s = summarize_walkforward(pf, ppy)
        pd.DataFrame([s]).to_csv(TAB / f'{study}_portfolio.csv')
        fig_pf = plotting.equity_curves(
            {f'top-{top_n} portfolio': pf.equity},
            f'{study}: walk-forward pair portfolio '
            f'(re-selected every {wf_cfg.trading} bars from formation data only)',
            FIG / f'{study}_portfolio.png')
        sel_lines = [f"- {r['start'].date()}: {', '.join(r['pairs']) or '(none)'}"
                     for r in pf.meta['selections'][:8]]
        md.append(f'\n### Walk-forward top-{top_n} portfolio\n')
        md.append(
            f'Pairs re-selected each window from formation data only '
            f'(corr ≥ {pf_corr}, EG p < {wf_cfg.coint_pvalue_gate}, half-life '
            f'gate), committed capital split into {top_n} fixed slots '
            f'(unfilled slots stay in cash). Sharpe **{s["sharpe"]:.2f}**, CAGR '
            f'{s["cagr_pct"]:.1f}%, max DD {s["max_dd_pct"]:.1f}%, '
            f'{s["n_trades"]:.0f} trades, NW t-stat {s["nw_tstat"]:.2f}.\n')
        md.append(f'\n![portfolio](figures/{Path(fig_pf).name})\n')
        md.append('\nFirst selections:\n' + '\n'.join(sel_lines) + '\n')

    # ------------------------------------------------ stocks: long-history view
    if study == 'stocks':
        try:
            prices = data.aligned_pair('stocks_long', 'JPM', 'BAC',
                                       start='1995-01-01')
            wf_l = _wf(prices, SIG_DEFAULT, eng, wf_cfg, 'JPM/BAC 1995-2018')
            s = summarize_walkforward(wf_l, 252)
            fig_l = plotting.equity_curves(
                {'JPM/BAC': wf_l.equity},
                'JPM/BAC 1995-2018: two decades out-of-sample',
                FIG / 'stocks_jpm_bac_long.png')
            fig_lg = plotting.gate_timeline(
                wf_l.windows, 'JPM/BAC 1995-2018: when was the pair tradable?',
                FIG / 'stocks_jpm_bac_long_gate.png')
            md.append('\n### Long-history check: JPM/BAC 1995-2018\n')
            md.append(
                f'Sharpe {s["sharpe"]:.2f}, CAGR {s["cagr_pct"]:.1f}%, '
                f'{s["n_trades"]:.0f} trades over {s["years"]:.0f} years; gate '
                f'open {s["gate_pass_pct"]:.0f}% of windows.\n')
            md.append(f'\n![long](figures/{Path(fig_l).name})\n')
            md.append(f'\n![longgate](figures/{Path(fig_lg).name})\n')
        except (KeyError, ValueError) as e:
            md.append(f'\n*Long-history check skipped: {e}*\n')

    frag = FRAG / f'{study}.md'
    frag.write_text('\n'.join(md) + '\n')
    (TAB / f'{study}_meta.json').write_text(json.dumps({
        'study': study, 'quick': quick, 'ppy': ppy, 'cost_bp': base_cost,
        'panel_shape': list(panel.shape),
        'start': str(panel.index.min().date()),
        'end': str(panel.index.max().date()),
    }, indent=2))
    return frag


def run_btpy_crosscheck(quick: bool = False) -> Path:
    """Cross-check the rule through the bundled backtesting.py engine."""
    _ensure_dirs()
    from .btpy_adapter import ratio_ohlc, run_backtestingpy
    from .signals import generate_signals, zscore
    rows = {}
    # Pairs whose price ratio is stable enough for the beta=1 single-instrument
    # mapping (an all-in short of a trending ratio, e.g. BTC/ETH 2016-17, gets
    # margin-called in backtesting.py — precisely why the two-leg engine is
    # the source of truth for headline results).
    cases = [('stocks', 'KO', 'PEP'), ('commodities', 'WTI', 'BRENT')]
    md = ['\n## Cross-check against backtesting.py\n',
          'The same z-score rule, run through the bundled `backtesting.py` '
          'engine on the *price-ratio* approximation (single instrument, '
          'beta=1, next-open execution, 2x per-side commission), against the '
          'two-leg engine on the same ratio signals. The two implementations '
          'are independent, so agreement on trade count and return sign '
          'validates the signal/timing plumbing; level differences reflect '
          'the documented approximation.\n']
    for cls, a, b in cases:
        prices = data.aligned_pair(cls, a, b, start=STUDY_START.get(cls))
        if cls == 'stocks':
            ohlc = ratio_ohlc(data.ohlc_for(a), data.ohlc_for(b))
        else:
            ohlc = ratio_ohlc(prices['a'], prices['b'])
        per_side = DEFAULT_COSTS_BP[cls]
        html = FIG / f'btpy_{a}_{b}.html'
        stats = run_backtestingpy(ohlc, SIG_DEFAULT, per_side,
                                  plot_path=None if quick else html)
        # two-leg engine on the identical ratio z-signals, beta fixed at 1
        ratio_z = zscore(np.log(prices['a'] / prices['b']), SIG_DEFAULT.z_window)
        sigs = generate_signals(ratio_z, SIG_DEFAULT)
        from .engine import backtest_pair
        eng = engine_config_for(cls)
        res = backtest_pair(prices, sigs['side'], 1.0, eng,
                            reasons=sigs['reason'], name=f'{a}/{b}')
        rows[f'{a}/{b} backtesting.py'] = {
            'return_pct': float(stats['Return [%]']),
            'sharpe': float(stats['Sharpe Ratio']),
            'max_dd_pct': -float(stats['Max. Drawdown [%]']),
            'n_trades': int(stats['# Trades']),
            'win_rate_pct': float(stats['Win Rate [%]']),
        }
        rows[f'{a}/{b} two-leg engine'] = {
            'return_pct': 100 * (res.equity.iloc[-1] - 1),
            'sharpe': float(summarize_walkforward(
                type('W', (), {'name': '', 'returns': res.returns,
                               'equity': res.equity, 'trades': res.trades,
                               'gate_pass_rate': float('nan')})(),
                PERIODS_PER_YEAR[cls])['sharpe']),
            'max_dd_pct': 100 * float((1 - res.equity /
                                       res.equity.cummax()).max()),
            'n_trades': len(res.trades),
            'win_rate_pct': 100 * float((res.trades['pnl'] > 0).mean())
            if len(res.trades) else float('nan'),
        }
    tab = pd.DataFrame(rows).T
    tab.to_csv(TAB / 'btpy_crosscheck.csv')
    md.append(_md_table(tab))
    md.append('\n*(Note: this cross-check is a full-sample single split with a '
              'rolling z — it validates plumbing, not performance; both runs '
              'here share the same in-sample caveats.)*\n')
    frag = FRAG / 'zz_btpy.md'
    frag.write_text('\n'.join(md) + '\n')
    return frag


ALL_STUDIES = ['crypto', 'stocks', 'forex', 'commodities', 'cross']
